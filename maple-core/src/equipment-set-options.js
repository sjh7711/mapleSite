export function knownEquipmentSetOptions(setName) {
  const key = setName
    .replace(/^(에테르넬|아케인셰이드|앱솔랩스) 세트\([^)]+\)$/u, "$1 세트")
    .replace(/^루타비스 세트\((?:궁수|해적)\)$/u, "루타비스 세트(전사)");
  return (Object.hasOwn(SET_OPTIONS, key) ? SET_OPTIONS[key] : []).map(
    ([set_count, set_option]) => ({ set_count, set_option }),
  );
}
