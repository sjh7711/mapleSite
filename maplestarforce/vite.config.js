import { cp, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { defineConfig, loadEnv } from "vite";
import { renderStarforceStartupShell } from "./src/shared/starforce-startup-shell.js";
import { renderStaticToolNav } from "./src/shared/tool-nav.js";

const __dirname = dirname(fileURLToPath(import.meta.url));

// The management HTML is a server-only module, never a public static asset.
// This also protects paths decoded differently by the static asset router.
function privateAdminPage() {
  return {
    name: "private-admin-page",
    apply: "build",
    async closeBundle() {
      const generated = resolve(__dirname, "functions/_generated");
      await mkdir(generated, { recursive: true });
      for (const [page, module] of [["starforce-prices", "starforce-admin-page"], ["blacksmith-inboxes", "starforce-inbox-admin-page"], ["soul-ether-prices", "soul-ether-admin-page"]]) {
        const html = await readFile(resolve(__dirname, `dist/admin/${page}/index.html`), "utf8");
        await writeFile(resolve(generated, `${module}.ts`),
          `// Generated by the production/preview build. Server only.\nexport default ${JSON.stringify(html)};\n`);
        await rm(resolve(__dirname, `dist/admin/${page}`), { recursive: true, force: true });
      }
    },
  };
}

// 모든 계산기와 안내 페이지에 같은 테마 전환을 제공한다.
function sharedTheme() {
  return {
    name: "shared-theme",
    transformIndexHtml: {
      order: "pre",
      async handler(html) {
        if (!html.includes('class="page"')) return html;
        const [bootstrap, toggle] = await Promise.all([
          readFile(resolve(__dirname, "src/shared/theme.js"), "utf8"),
          readFile(resolve(__dirname, "partials/theme-toggle.html"), "utf8"),
        ]);
        return html
          .replace(/(<meta charset="utf-8"\s*\/>)/u, `$1\n<script>${bootstrap}</script>`)
          .replace("</header>", `${toggle}\n</header>`);
      },
    },
  };
}

// Google이 JavaScript 렌더링 전에도 계산기 링크를 발견하도록 한다.
function staticToolNav() {
  return {
    name: "static-tool-nav",
    transformIndexHtml: {
      order: "pre",
      handler(html, context) {
        if (!html.includes('id="toolnav"')) return html;
        const page = Object.entries(pages).find(([, filename]) => filename === context.filename)?.[0];
        if (!page) throw new Error(`계산기 메뉴의 페이지를 확인하지 못했습니다: ${context.filename}`);
        const current = page === "main" ? "starforce" : page === "additional" ? "potential" : page;
        return html.replace(
          /(<nav\b[^>]*\bid="toolnav"[^>]*>)[\s\S]*?(<\/nav>)/u,
          (_, open, close) => `${open}\n${renderStaticToolNav(current)}\n${close}`,
        );
      },
    },
  };
}

// 빌드된 HTML에 안내 링크를 넣어 JavaScript 없이도 읽을 수 있게 한다.
function sharedSiteFooter() {
  return {
    name: "shared-site-footer",
    transformIndexHtml: {
      order: "pre",
      async handler(html, context) {
        if (!html.includes("<!-- site-footer -->")) return html;
        const footer = await readFile(
          resolve(__dirname, "partials/site-footer.html"), "utf8",
        );
        const copyButton = context.filename === resolve(__dirname, "index.html")
          ? ' <button id="contact-copy" class="page__copy" type="button" aria-label="문의 이메일 주소 복사">복사</button>'
          : "";
        return html.replace("<!-- site-footer -->", footer.replace("<!-- contact-copy -->", copyButton));
      },
    },
  };
}

// First-screen CSS/geometry and recovery are available before dynamic chunks.
function calculatorStartup() {
  let env;
  return {
    name: "calculator-startup",
    configResolved(config) { env = loadEnv(config.mode, __dirname); },
    transformIndexHtml: {
      order: "pre",
      async handler(html) {
        if (!html.includes("data-calculator=")) return html;
        const bootstrap = await readFile(resolve(__dirname, "src/shared/calculator-startup-recovery.js"), "utf8");
        html = html.replace("</head>", `<link rel="stylesheet" href="/src/shared/calculator-startup.css"><script>${bootstrap}</script></head>`)
          .replace('<script type="module" src=', '<script id="calculator-entry" type="module" src=')
          .replace("</header>", `</header><div id="calculator-startup-error" class="calculator-startup-error" role="alert" hidden><span></span><button type="button" class="result-share-action">다시 시도</button></div>`);
        if (html.includes('data-calculator="starforce"')) {
          html = renderStarforceStartupShell(html, {
            textTransfer: env.VITE_STARFORCE_TEXT_TRANSFER_ENABLED === "true",
            inbox: env.VITE_STARFORCE_INBOX_ENABLED === "true",
          });
        }
        return html;
      },
    },
  };
}

// 시세 서비스가 관리하는 데이터는 계산기 앱과 별도로 보관·배포한다.
function applicationPublicAssets() {
  return {
    name: "application-public-assets",
    apply: "build",
    async writeBundle() {
      const publicRoot = resolve(__dirname, "public");
      for (const entry of await readdir(publicRoot, { withFileTypes: true })) {
        if (entry.name === "item-market") continue;
        await cp(resolve(publicRoot, entry.name), resolve(__dirname, "dist", entry.name), { recursive: true });
      }
    },
  };
}

